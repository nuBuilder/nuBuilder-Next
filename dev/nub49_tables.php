<?php
/*
 * Writes install/nubuilder49_tables.sql – the table definitions of nuBuilder 4.9 (no data) – from nuBuilder's nubuilder4.sql:
 *
 *     php dev/nub49_tables.php <path>/nubuilder4.sql
 *
 * Used by the installer (NuInstall::upgradeTo49) to bring a nubuilder4.sql of an older 4.x version to the 4.9 structure:
 * CREATE TABLE IF NOT EXISTS with the primary key and indexes of the dump's ALTER TABLE … ADD PRIMARY KEY / ADD KEY statements.
 */
declare(strict_types=1);

define('NU_ROOT', dirname(__DIR__));
if (!function_exists('t')) { function t(string $k, ...$a): string { return $k; } }
require NU_ROOT . '/core/nuinstall.php';

$src = $argv[1] ?? '';
if ($src === '' || !is_file($src)) { fwrite(STDERR, "usage: php dev/nub49_tables.php <nubuilder4.sql>\n"); exit(1); }

$create = []; $keys = [];
foreach (NuInstall::splitSql((string)file_get_contents($src)) as $s) {
	if (preg_match('/^CREATE TABLE `(zzzzsys_\w+)`\s*\((.*)\)\s*ENGINE/is', $s, $m)) {
		$create[$m[1]] = array_values(array_filter(array_map('trim', preg_split('/,\s*\n/', trim($m[2])) ?: [])));
	} elseif (preg_match('/^ALTER TABLE `(zzzzsys_\w+)`\s+(ADD .*)$/is', $s, $m)) {
		foreach (preg_split('/,\s*\n\s*/', trim($m[2])) ?: [] as $part) {
			if (preg_match('/^ADD\s+((?:PRIMARY|UNIQUE)?\s*KEY.*)$/is', trim($part), $k)) $keys[$m[1]][] = trim($k[1]);
		}
	}
}
ksort($create);
$out = "-- nuBuilder 4.9 table definitions (no data), generated by dev/nub49_tables.php from nubuilder4.sql – do not edit.\n"
	. "-- The installer creates missing tables from it when a nubuilder4.sql of an older 4.x version was imported (NuInstall::upgradeTo49).\n\n";
foreach ($create as $t => $cols) {
	$out .= "CREATE TABLE IF NOT EXISTS `$t` (\n  " . implode(",\n  ", array_merge($cols, $keys[$t] ?? [])) . "\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n\n";
}
file_put_contents(NU_ROOT . '/install/nubuilder49_tables.sql', $out);
echo count($create), " tables written to install/nubuilder49_tables.sql\n";
