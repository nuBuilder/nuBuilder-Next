#!/usr/bin/env python3
"""Join the form runtime (code review L1): dev/src/nuruntime/*.js in name order -> assets/js/nu/nuruntime.js.

The parts are pieces of ONE function (they share its variables), so they are not valid scripts on their own; the joined file is what
the pages load, ESLint checks and dev/minify.py shrinks. Edit the parts, never assets/js/nu/nuruntime.js – dev/release.py runs this
before its checks and dev/tests/run.php fails when the joined file differs from the parts.
    python3 -I dev/nuruntime_join.py [--check]     (--check: exit 1 when assets/js/nu/nuruntime.js is not the join of the parts)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'dev', 'src', 'nuruntime')
OUT = os.path.join(ROOT, 'assets', 'js', 'nu', 'nuruntime.js')
BANNER = '/* GENERATED by dev/nuruntime_join.py from dev/src/nuruntime/*.js (code review L1) – edit the parts there, not this file */'


def joined() -> str:
    names = sorted(n for n in os.listdir(SRC) if n.endswith('.js'))
    parts = []
    for n in names:
        with open(os.path.join(SRC, n), encoding='utf-8') as fh:
            parts.append(fh.read())
    text = ''.join(parts)
    first, _, rest = text.partition('\n')
    return first + '\n' + BANNER + '\n' + rest


def main() -> int:
    want = joined()
    have = ''
    if os.path.isfile(OUT):
        with open(OUT, encoding='utf-8') as fh:
            have = fh.read()
    if '--check' in sys.argv:
        if have != want:
            print('assets/js/nu/nuruntime.js is not the join of dev/src/nuruntime/ – run python3 -I dev/nuruntime_join.py')
            return 1
        return 0
    if have != want:
        with open(OUT, 'w', encoding='utf-8') as f:
            f.write(want)
        print('nuruntime.js: joined from', len([n for n in os.listdir(SRC) if n.endswith('.js')]), 'parts')
    return 0


if __name__ == '__main__':
    sys.exit(main())
